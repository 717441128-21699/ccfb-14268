import { chromium } from 'playwright';
import { createServer } from 'vite';
const server = await createServer({ server: { port: 5195, host: '127.0.0.1' }, logLevel: 'error' });
await server.listen();
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1680, height: 1050 }, deviceScaleFactor: 1.5 });
page.on('pageerror', (e) => console.log('PAGEERROR:', String(e)));
await page.goto('http://127.0.0.1:5195/', { waitUntil: 'commit' });
await page.waitForSelector('text=案件列表');
await page.click('text=＋ 新建案件');
await page.locator('.modal input').nth(1).fill('截图验收案');
await page.click('.modal button:has-text("建档")');
await page.click('.topbar button:has-text("新建检验文书")');
await page.waitForSelector('.modal');
await page.selectOption('.modal select', { label: 'A4 @200DPI 1654×2339（性能验收口径）' });
await page.locator('.modal').evaluate((el) => el.scrollTo(0, el.scrollHeight));
await page.locator('.modal button.primary', { hasText: '生成并进入检验' }).evaluate((b) => b.click());
await page.waitForSelector('text=GPU 分离耗时', { timeout: 60000 });
await page.waitForTimeout(1500);
await page.screenshot({ path: 'e2e/shot-split.png' });
await page.click('button:has-text("墨水二层（后加墨）")');
await page.waitForTimeout(400);
await page.screenshot({ path: 'e2e/shot-ink2.png' });
await page.click('button:has-text("墨水一层（原文墨）")');
await page.waitForTimeout(400);
await page.screenshot({ path: 'e2e/shot-ink1.png' });
await page.click('button:has-text("拟合残差图")');
await page.waitForTimeout(400);
await page.screenshot({ path: 'e2e/shot-residual.png' });
// 报告页
const dl = page.waitForEvent('download');
await page.click('button:has-text("生成结论页")');
await page.fill('textarea', '经六波段反射率逐像素解混，金额处后加笔画与原文字墨分层清晰，认定为两种墨水两次书写。');
await page.click('button:has-text("导出报告 PNG")');
const d = await dl;
await d.saveAs('e2e/shot-report.png');
console.log('screenshots done');
await browser.close();
await server.close();
