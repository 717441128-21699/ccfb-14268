/** 伪书写回退：按字符编码种子生成 4~6 条类笔画折线，保证同字同形 */
export function pseudoGlyph(ch: string): Glyph {
  let h = 0;
  for (let i = 0; i < ch.length; i++) h = (h * 131 + ch.charCodeAt(i)) >>> 0;
  let s = h || 1;
  const rnd = () => {
    s = (s * 1664525 + 1013904223) >>> 0;
    return s / 4294967296;
  };
  const strokes: Glyph = [];
  const n = 4 + Math.floor(rnd() * 3);
  for (let i = 0; i < n; i++) {
    const x = 18 + rnd() * 60;
    const y = 14 + rnd() * 20;
    const vertical = rnd() > 0.45;
    if (vertical) strokes.push([x, y, x + (rnd() - 0.5) * 20, y + 30 + rnd() * 40]);
    else strokes.push([14 + rnd() * 20, y, 70 + rnd() * 16, y + (rnd() - 0.5) * 14]);
  }
  return strokes;
}

export function getGlyph(ch: string): Glyph {
  return GLYPHS[ch] ?? pseudoGlyph(ch);
}
